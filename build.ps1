# build.ps1 - build PowerToggle.exe
# Auto-detects MinGW-w64 (g++/windres) or MSVC (cl/rc).
# Each build bumps the patch version in version.txt and emits:
#   build\PowerToggle-<version>.exe   (versioned artifact, kept)
#   build\PowerToggle.exe             (copy for convenience)
$ErrorActionPreference = "Stop"

$Root   = $PSScriptRoot
$SrcDir = Join-Path $Root "src"
$ResDir = Join-Path $Root "res"
$Build  = Join-Path $Root "build"

New-Item -ItemType Directory -Force -Path $Build | Out-Null

# ---------- version bump ----------
$VerFile = Join-Path $Root "version.txt"
$VerHdrPath = Join-Path $SrcDir "version.h"

if (-not (Test-Path $VerFile)) {
    [System.IO.File]::WriteAllText($VerFile, "1.0.0", [System.Text.Encoding]::ASCII)
}
$old = ([System.IO.File]::ReadAllText($VerFile)).Trim()
$parts = $old.Split('.')
if ($parts.Count -lt 3) { $parts = @("1", "0", "0") }
$vMajor = [int]$parts[0]
$vMinor = [int]$parts[1]
$vPatch = [int]$parts[2] + 1
$Ver = "$vMajor.$vMinor.$vPatch"
[System.IO.File]::WriteAllText($VerFile, $Ver, [System.Text.Encoding]::ASCII)

$verHdrText = @"
/* version.h - generated by build.ps1 from version.txt, do not edit */
#ifndef PT_VERSION_H
#define PT_VERSION_H

#define PT_VER_MAJOR $vMajor
#define PT_VER_MINOR $vMinor
#define PT_VER_PATCH $vPatch
#define PT_VER_BUILD 0

#define PT_VER_STR  "$Ver"
#define PT_VER_WSTR L"$Ver"

#endif /* PT_VERSION_H */
"@
[System.IO.File]::WriteAllText($VerHdrPath, $verHdrText, [System.Text.Encoding]::ASCII)
Write-Host "[build] version: $old -> $Ver"

$OutExe    = Join-Path $Build "PowerToggle.exe"
$OutExeVer = Join-Path $Build ("PowerToggle-" + $Ver + ".exe")
$ResObj    = Join-Path $Build "app.res"

$Sources = @(Get-ChildItem $SrcDir -Filter *.cpp | ForEach-Object { $_.FullName })
if ($Sources.Count -eq 0) { throw "No .cpp files found in src" }

# 上一次的实例若仍在运行会锁住 exe，导致链接报 Permission denied
$running = @(Get-Process -Name PowerToggle -ErrorAction SilentlyContinue)
if ($running.Count -gt 0) {
    Write-Host "[build] stopping $($running.Count) running instance(s) to unlock output"
    $running | Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Milliseconds 600
}

$hasGpp = Get-Command g++ -ErrorAction SilentlyContinue
$hasCl  = Get-Command cl  -ErrorAction SilentlyContinue

if ($hasGpp) {
    Write-Host "[build] toolchain: MinGW-w64 (g++)"
    $windres = Get-Command windres -ErrorAction SilentlyContinue
    if (-not $windres) { throw "windres not found; MinGW-w64 installation is incomplete" }

    & $windres.Source -I $ResDir -I $SrcDir --codepage=65001 -O coff -F pe-x86-64 -o $ResObj (Join-Path $ResDir "app.rc")
    if ($LASTEXITCODE -ne 0) { throw "windres failed" }

    $clArgs = @("-std=c++17", "-O2", "-s", "-mwindows", "-municode", "-DUNICODE", "-D_UNICODE",
                "-Wall", "-Wextra", "-I", $SrcDir, "-o", $OutExeVer) + $Sources + @($ResObj,
                "-lpowrprof", "-lshell32", "-lole32", "-lcomctl32", "-lcomdlg32",
                "-lgdi32", "-luser32", "-ladvapi32")
    & g++ @clArgs
    if ($LASTEXITCODE -ne 0) { throw "g++ failed" }

} elseif ($hasCl) {
    Write-Host "[build] toolchain: MSVC (cl)"
    & rc /nologo /c 65001 /I $ResDir /I $SrcDir /fo $ResObj (Join-Path $ResDir "app.rc")
    if ($LASTEXITCODE -ne 0) { throw "rc failed" }

    $mfcArgs = @("/nologo", "/utf-8", "/O2", "/MT", "/GR-", "/DUNICODE", "/D_UNICODE",
                 "/I", $SrcDir, ("/Fo" + $Build + "\")) + $Sources + @(
                 "/link", "/SUBSYSTEM:WINDOWS", "/MANIFEST:NO",
                 $ResObj, "user32.lib", "gdi32.lib", "shell32.lib", "comdlg32.lib",
                 "comctl32.lib", "powrprof.lib", "advapi32.lib", "ole32.lib",
                 ("/OUT:" + $OutExeVer))
    & cl @mfcArgs
    if ($LASTEXITCODE -ne 0) { throw "cl failed" }

} else {
    throw "No C++ compiler found. Install MinGW-w64 (g++ + windres) or Visual Studio Build Tools."
}

if (-not (Test-Path $OutExeVer)) { throw "Build finished but output not found" }
Copy-Item -Path $OutExeVer -Destination $OutExe -Force

$kb = [math]::Round((Get-Item $OutExeVer).Length / 1KB, 1)
Write-Host "[build] OK: $OutExeVer ($kb KB)"
Write-Host "[build] copy: $OutExe"
